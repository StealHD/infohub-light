import AxeBuilder from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'
import { installAgentApi, installGatewayFixture } from './agentWorkspaceFixtures'

async function connect(page: Page) {
  await installAgentApi(page, true)
  await installGatewayFixture(page, true)
  await page.goto('/agent')
  await page.getByLabel(/Gateway token 或 dashboard 地址/u).fill('fixture-token')
  await page.getByRole('button', { name: '连接并授权' }).click()
  await expect(page.getByText('Gateway 已连接').first()).toBeAttached()
}

test('directory pages beyond 200, searches archives and restores the selected Agent', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'desktop', 'desktop exercises the directory protocol')
  await connect(page)
  const sidebar = page.locator('[data-agent-workspace-sidebar]')
  await expect(sidebar.locator('[data-agent-session-row]')).toHaveCount(3)
  await page.getByRole('button', { name: '全部会话', exact: true }).click()
  const history = page.getByRole('dialog', { name: '全部会话' })
  for (let pageIndex = 0; pageIndex < 4; pageIndex += 1) {
    await history.getByRole('button', { name: '下一页' }).click()
    await expect(history.getByRole('button', { name: `打开会话：历史记录 ${String((pageIndex + 1) * 50 - 1).padStart(3, '0')}`, exact: true })).toBeVisible()
  }
  await expect(history.getByRole('button', { name: '打开会话：历史记录 204', exact: true })).toBeVisible()
  await history.getByText('查看已归档会话', { exact: true }).click()
  await expect(history.getByRole('checkbox')).toBeChecked()
  await expect(history.getByRole('button', { name: '打开会话：归档记录' })).toBeVisible()
  await history.getByRole('checkbox').focus()
  await history.getByRole('checkbox').press('Space')
  await expect(history.getByRole('checkbox')).not.toBeChecked()
  await history.getByLabel('搜索会话').fill('历史记录 204')
  await expect(history.locator('[data-agent-session-row]')).toHaveCount(1)
  await history.getByRole('button', { name: '打开会话：历史记录 204', exact: true }).click()
  await expect(history).toBeHidden()
  await expect(page.getByRole('heading', { level: 1, name: '历史记录 204' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { level: 1, name: '历史记录 204' })).toBeVisible()
  const requests = await page.evaluate(() => (window as unknown as { __gatewayRequests: Array<{ method: string; params: Record<string, unknown> }> }).__gatewayRequests)
  expect(requests.find((request) => request.method === 'tools.effective')?.params).toMatchObject({ sessionKey: 'agent:research:dashboard:204', agentId: 'research' })
  expect(requests.filter((request) => ['sessions.create', 'chat.send'].includes(request.method))).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('directory-restored.png') })
})

