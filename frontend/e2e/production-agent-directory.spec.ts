test('compact composer, examples draft continuity and account menu work across viewports', async ({ page }, testInfo) => {
  await connect(page)
  const composer = page.getByTestId('openclaw-composer-textarea')
  const form = page.locator('.agent-workspace-composer')
  const size = await form.boundingBox()
  expect(size?.height).toBeLessThanOrEqual(testInfo.project.name === 'mobile' ? 140 : 128)
  const toolbar = page.getByTestId('openclaw-composer-toolbar')
  const model = await toolbar.getByRole('button', { name: /OpenClaw 模型/u }).boundingBox()
  const attachment = await toolbar.getByRole('button', { name: /附件|图片/u }).first().boundingBox()
  expect(model!.x).toBeGreaterThan(attachment!.x)
  await composer.fill('这段中文草稿需要保留')
  if (['mobile', 'compact-desktop'].includes(testInfo.project.name)) await page.getByRole('button', { name: '打开 OpenClaw 会话' }).click()
  await page.getByRole('link', { name: '使用示例', exact: true }).click()
  await expect(page).toHaveURL(/\/agent\/examples$/u)
  await page.goBack()
  await expect(composer).toHaveValue('这段中文草稿需要保留')
  await composer.fill(Array.from({ length: 30 }, (_, index) => `长输入第 ${index} 行`).join('\n'))
  expect(await composer.evaluate((element) => element.scrollHeight > element.clientHeight)).toBe(true)
  expect((await composer.boundingBox())!.height).toBeLessThanOrEqual(180)
  if (['mobile', 'compact-desktop'].includes(testInfo.project.name)) await page.getByRole('button', { name: '打开 OpenClaw 会话' }).click()
  await page.getByRole('button', { name: '打开账户菜单', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出登录', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('[data-account-menu-surface]')).not.toBeAttached()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  const results = await new AxeBuilder({ page }).analyze()
  expect(results.violations.filter((violation) => ['serious', 'critical'].includes(violation.impact ?? ''))).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('compact-composer.png') })
})

test('docked panels retain closing content, reverse smoothly and restore focus', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'desktop', 'docked panels require the wide layout')
  await connect(page)
  const trigger = page.getByRole('button', { name: '打开上下文' })
  await trigger.click()
  const panel = page.getByRole('complementary', { name: '上下文检查器' })
  await expect(panel).toHaveCSS('width', '360px')
  const close = panel.getByRole('button', { name: '关闭上下文', exact: true })
  await close.click()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(panel).toHaveCSS('width', '360px')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await close.click()
  await expect(page.locator('.disclosure-panel')).toHaveCSS('width', '0px')
  await expect(page.locator('.disclosure-panel')).toHaveAttribute('inert', '')
  await trigger.click()
  await expect(panel).toHaveCSS('transition-duration', '0s')
})


test('session menu confirms deletion and refreshes the sidebar and history', async ({ page }, testInfo) => {
  await connect(page)
  if (['mobile', 'compact-desktop'].includes(testInfo.project.name)) await page.getByRole('button', { name: '打开 OpenClaw 会话' }).click()
  const sidebar = page.locator('[data-agent-workspace-sidebar]')
  await sidebar.getByRole('button', { name: '会话详情：历史记录 000', exact: true }).click()
  await page.getByRole('button', { name: '删除会话', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: '删除会话', exact: true })
  await expect(confirmation).toBeVisible()
  await confirmation.getByRole('button', { name: '取消', exact: true }).click()
  await expect(confirmation).toBeHidden()
  await page.keyboard.press('Escape')
  await sidebar.getByRole('button', { name: '会话详情：历史记录 000', exact: true }).click()
  await page.getByRole('button', { name: '删除会话', exact: true }).click()
  await confirmation.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(confirmation).toBeHidden()
  await expect(sidebar.getByRole('button', { name: '打开会话：历史记录 000', exact: true })).toHaveCount(0)
  await sidebar.getByRole('button', { name: '全部会话', exact: true }).click()
  const history = page.getByRole('dialog', { name: '全部会话', exact: true })
  await history.getByLabel('搜索会话').fill('历史记录 000')
  await expect(history.getByText('没有匹配的会话')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
})
