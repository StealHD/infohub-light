async function resolvedThemeColor(locator: import('@playwright/test').Locator, token: string) {
  return locator.evaluate((node, token) => {
    const probe = document.createElement('span')
    probe.hidden = true; probe.style.color = `var(${token})`; node.append(probe)
    const color = getComputedStyle(probe).color
    probe.remove(); return color
  }, token)
}

async function expectCenteredEffort(page: Page) {
  const geometry = await page.locator('.effort-slider-track').evaluate((track) => {
    const bounds = track.getBoundingClientRect()
    const style = getComputedStyle(track)
    const inset = parseFloat(style.borderLeftWidth)
    const width = bounds.width - inset - parseFloat(style.borderRightWidth)
    const center = (node: Element) => { const box = node.getBoundingClientRect(); return { x: box.x + box.width / 2, y: box.y + box.height / 2 } }
    const marks = Array.from(track.querySelectorAll('.effort-slider-marks > span')).map(center)
    const index = Number(track.querySelector('input')?.value)
    return { bounds: { x: bounds.x, y: bounds.y, height: bounds.height }, inset, width, marks, index, thumb: center(track.querySelector('.effort-slider-thumb')!) }
  })
  expect(geometry.inset).toBe(geometry.bounds.height / 2)
  geometry.marks.forEach((mark, index) => {
    expect(Math.abs(mark.x - (geometry.bounds.x + geometry.inset + index * geometry.width / (geometry.marks.length - 1)))).toBeLessThan(.75)
    expect(Math.abs(mark.y - (geometry.bounds.y + geometry.bounds.height / 2))).toBeLessThan(.75)
  })
  expect(Math.abs(geometry.thumb.x - geometry.marks[geometry.index].x)).toBeLessThan(.75)
  expect(Math.abs(geometry.thumb.y - geometry.marks[geometry.index].y)).toBeLessThan(.75)
  const labelFits = await page.locator('.effort-model-trigger').evaluate((button) => {
    const bounds = button.getBoundingClientRect()
    return Array.from(button.children).every((child) => { const box = child.getBoundingClientRect(); return box.top >= bounds.top && box.bottom <= bounds.bottom + .5 })
  })
  expect(labelFits).toBe(true)
}

