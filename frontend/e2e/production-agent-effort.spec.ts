  await expect(fastTooltip).not.toHaveAttribute('data-entering', 'true')
  await expect(page.locator('.effort-picker-surface')).toHaveCSS('opacity', '1')
  const tipBounds = await fastTooltip.boundingBox()
  expect(tipBounds!.y + tipBounds!.height).toBeLessThanOrEqual((await fast.boundingBox())!.y)
  const panelBounds = (await page.locator('.effort-picker-surface').boundingBox())!
  const captureX = Math.max(0, Math.min(tipBounds!.x, panelBounds.x) - 8)
  const captureY = Math.max(0, tipBounds!.y - 8)
  await page.screenshot({ path: testInfo.outputPath('fast-tooltip-above.png'), clip: { x: captureX, y: captureY, width: Math.min(page.viewportSize()!.width - captureX, panelBounds.x + panelBounds.width - captureX + 8), height: panelBounds.y + panelBounds.height - captureY + 8 } })
