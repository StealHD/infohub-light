import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import { installShortcutFixture, shortcutRequests } from './fixtures/agent-shortcuts'

test.beforeEach(async ({ page }) => {
  await installShortcutFixture(page)
  await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: 'dark' })
  await page.goto('/agent')
  await page.getByLabel(/Gateway token 或 dashboard 地址/u).fill('fixture-token')
  await page.getByRole('button', { name: '连接并授权' }).click()
  await expect(page.getByTestId('openclaw-composer-textarea')).toBeVisible()
})

test('shared shortcut menu selects without sending and verifies Skill before chat.send', async ({ page }, testInfo) => {
  const input = page.getByTestId('openclaw-composer-textarea')
  await input.fill('@天气')
  const option = page.getByRole('option', { name: /weather/u })
  await expect(option).toBeVisible()
  await expect(input).toBeFocused()
  const bounds = await option.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  expect(bounds!.height).toBeGreaterThanOrEqual(44)
  expect((await new AxeBuilder({ page }).include('[data-testid="openclaw-composer-dock"]').include('[role="listbox"]').analyze()).violations).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('shortcut-menu.png') })
  await input.press('Enter')
  await expect(page.getByText('Skill：weather', { exact: true })).toBeVisible()
  expect((await shortcutRequests(page)).filter((item) => item.method === 'chat.send')).toHaveLength(0)
  await input.fill('检查天气')
  await input.press('Enter')
  await expect(page.getByText('模拟请求已完成')).toBeVisible()
  const requests = await shortcutRequests(page)
  expect(requests.filter((item) => item.method === 'skills.status')).toHaveLength(2)
  const sends = requests.filter((item) => item.method === 'chat.send')
  expect(sends).toHaveLength(1)
  expect(sends[0].params.message).toContain('\n$weather\n')
  expect(requests.some((item) => item.method === 'skills.run' || item.method === 'skills.update')).toBe(false)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('revoked Skill keeps the draft and never sends, while new cancellation does not create', async ({ page }) => {
  const input = page.getByTestId('openclaw-composer-textarea')
  await input.fill('/weather'); await expect(page.getByRole('option', { name: /weather/u })).toBeVisible(); await input.press('Enter')
  await page.evaluate(() => { (window as unknown as { shortcutFixture: { enabled: boolean } }).shortcutFixture.enabled = false })
  await input.fill('保留问题'); await input.press('Enter')
  await expect(page.getByText('无法确认本次 Skill 仍可调用。草稿已保留，请移除 Skill 或重试。')).toBeVisible()
  await expect(input).toHaveValue('保留问题')
  expect((await shortcutRequests(page)).filter((item) => item.method === 'chat.send')).toHaveLength(0)
  const before = (await shortcutRequests(page)).filter((item) => item.method === 'sessions.create').length
  await input.fill('保留问题 /new'); await input.press('Enter')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(input).toHaveValue('保留问题 ')
  expect((await shortcutRequests(page)).filter((item) => item.method === 'sessions.create')).toHaveLength(before)
})

