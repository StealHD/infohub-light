test('Skill draft follows SPA switching into the narrow Feed rail and back', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'desktop', 'The fixed 320 px Feed rail is desktop-only')
  await page.evaluate(() => localStorage.setItem('inteliscope.ui.right-rail.v1:shortcuts', JSON.stringify({ width: 320 })))
  const input = page.getByTestId('openclaw-composer-textarea')
  await input.fill('@天气'); await expect(page.getByRole('option', { name: /weather/u })).toBeVisible(); await input.press('Enter')
  await input.fill('跨工作区草稿')
  const before = (await shortcutRequests(page)).filter((item) => item.method === 'connect').length
  await page.getByRole('button', { name: '切换工作区，当前为 OpenClaw' }).click()
  await page.getByRole('button', { name: 'Inscope 订阅、阅读与追踪' }).click()
  await page.getByRole('button', { name: '展开 Agent 面板' }).click()
  await expect(input).toHaveValue('跨工作区草稿')
  await expect(page.getByText('Skill：weather', { exact: true })).toBeVisible()
  const rail = page.getByRole('complementary', { name: 'OpenClaw 上下文' })
  const separator = page.getByRole('separator', { name: '调整信息流和 Agent 面板宽度' })
  await separator.focus(); await separator.press('Home')
  await input.fill('/')
  await expect(page.getByRole('listbox', { name: 'Agent 快捷候选' })).toBeVisible()
  expect(Math.round((await rail.boundingBox())!.width)).toBe(320)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await input.press('Escape')
  await page.getByRole('button', { name: '在 Agent 工作台打开' }).click()
  await expect(page.getByText('Skill：weather', { exact: true })).toBeVisible()
  expect((await shortcutRequests(page)).filter((item) => item.method === 'connect')).toHaveLength(before)
})

test('menu remains bounded in light theme and zoom-equivalent viewport', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'desktop', 'Dedicated zoom and light-theme fixture')
  await page.getByRole('button', { name: '切换到白天模式' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.setViewportSize({ width: 720, height: 450 })
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
  const input = page.getByTestId('openclaw-composer-textarea')
  await input.fill('/')
  const menu = page.getByRole('listbox', { name: 'Agent 快捷候选' })
  await expect(menu).toBeVisible()
  const box = await menu.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(720)
  await expect(input).toBeFocused()
  expect((await new AxeBuilder({ page }).include('[data-testid="openclaw-composer-dock"]').include('[role="listbox"]').analyze()).violations).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('shortcut-light-zoom.png') })
})
